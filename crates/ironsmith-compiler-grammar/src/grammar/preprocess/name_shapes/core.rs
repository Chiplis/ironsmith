            | "then"
            | "at"
            | "for"
            | "from"
            | "out"
            | "until"
            | "during"
            | "turn"
            | "without"
            | "with"
            | "first"
            | "second"
            | "third"
            | "fourth"
            | "fifth"
            | "sixth"
            | "seventh"
            | "eighth"
            | "ninth"
            | "tenth"
            | "last"
            | "next"
            | "additional"
            | "alternative"
            | "target"
            | "targets"
            | "targeted"
            | "add"
            | "added"
            | "move"
            | "moved"
            | "deal"
            | "deals"
            | "dealt"
            | "damaged"
            | "draw"
            | "draws"
            | "drawn"
            | "counter"
            | "countered"
            | "double"
            | "doubles"
            | "doubled"
            | "destroy"
            | "destroyed"
            | "exile"
            | "untap"
            | "tapped"
            | "untapped"
            | "scry"
            | "discard"
            | "discarded"
            | "transform"
            | "transformed"
            | "regenerate"
            | "mill"
            | "milled"
            | "get"
            | "reveal"
            | "revealed"
            | "look"
            | "prevent"
            | "prevents"
            | "prevented"
            | "lose"
            | "lost"
            | "gain"
            | "gained"
