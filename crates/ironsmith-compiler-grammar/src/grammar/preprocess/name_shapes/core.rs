            | "blocking"
            | "attacking"
            | "top"
            | "bottom"
            | "same"
            | "different"
            | "villainous"
            | "chosen"
            | "named"
            | "counted"
            | "rounded"
            | "rest"
            | "source"
            | "color"
            | "copy"
            | "clash"
            | "coin"
            | "radiance"
            | "station"
