#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn every_serialized_effect_has_an_explicit_library_contract() {
        let registry = include_str!("../../ironsmith-artifact-effect-decoder/effect-registry.tsv");
        for row in registry
            .lines()
            .filter(|row| !row.is_empty() && !row.starts_with('#'))
        {
            let kind = row.split('\t').next().unwrap();
            assert_ne!(
                library_movement_policy(kind),
                LibraryMovementPolicy::Unknown,
                "missing structural contract: {kind}"
            );
        }
    }
    #[test]
    fn unknown_callback_is_not_a_known_safe_leaf() {
        assert_eq!(
            library_movement_policy("test::UnmodeledCallback"),
            LibraryMovementPolicy::Unknown
        );
    }
}
