//! Explicit structural contracts for the executable effect vocabulary.
//!
//! This table is shared by compiler and runtime payloads. Unknown callbacks
//! must not silently claim that they are safe activated mana abilities.
//! Effect kinds retain their names across artifact compatibility adapters.

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum LibraryMovementPolicy {
    /// A primitive whose own operation cannot move cards across a library boundary.
    Leaf,
    /// Owned programs run later, not during the current instruction.
    Deferred,
    /// An operation whose authored semantics include library movement.
    Moves,
    /// Requires payload-aware origin tracking or immediate child traversal.
    Inspect,
    /// No semantic declaration exists; conservatively disqualify mana handling.
    Unknown,
}

