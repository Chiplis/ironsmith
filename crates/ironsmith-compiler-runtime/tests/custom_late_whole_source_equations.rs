#[test]
fn all_198_physical_sources_and_234_complete_faces_strictly_compile_through_independent_routes(){
    let fixture=input();let rows=fixture["mechanics"].as_array().unwrap();assert_eq!(rows.len(),12);
    let mut keys=BTreeSet::new();let mut failures=Vec::new();let mut faces_passed=0;
    for row in rows {for card in row["representative_cards"].as_array().unwrap(){
        let key=card["source_card_key"].as_str().unwrap();assert!(keys.insert(key.to_owned()),"duplicate physical source {key}");
        let originals=card["source_faces"].as_array().unwrap();let raw=&card["raw_source_record"];
        assert_eq!(raw["key"],key,"source key must remain authoritative");assert_eq!(card["source_shape"],raw["shape"]);
        assert_eq!(originals.len(),if raw["cardName2"].as_str().is_some_and(|name|!name.is_empty()){2}else{1},"linked face evidence cannot disappear");
        for (index,face) in originals.iter().enumerate(){
            let suffix=if index==0{""}else{"2"};let field=|name:&str|format!("{name}{suffix}");
            assert_eq!(face["source_rules_text"],raw[&field("rulesText")]);assert_eq!(face["name"],raw[&field("cardName")]);
            assert_eq!(face["source_type_line"],raw[&field("typeLine")]);assert_eq!(face["source_mana_cost"],raw[&field("manaCost")]);assert_eq!(face["source_color"],raw[&field("color")]);
            assert!(face["original_text"].as_str().unwrap().ends_with(face["source_rules_text"].as_str().unwrap()),"whole printed body must remain {key}");
        }
        let result=std::panic::catch_unwind(std::panic::AssertUnwindSafe(||custom_final_next_wave_support::linked_definitions(card)));
        match result {
            Ok(Ok(pairs))=>{assert_eq!(pairs.len(),originals.len(),"source faces changed: {key}");faces_passed+=pairs.len();for(index,[native,wire])in pairs.into_iter().enumerate(){assert_eq!(native.card.name,originals[index]["name"].as_str().unwrap());assert_eq!(native.card.name,wire.card.name);assert_eq!(ironsmith_text::compiled_text_lines(&native),ironsmith_text::compiled_text_lines(&wire),"independent route text mismatch: {key} face{index}");}},
            Ok(Err(error))=>failures.push(format!("{key}: {error}")),Err(_)=>failures.push(format!("{key}: compiler panic; retain exact diagnostic above")),
        }
    }}
    assert_eq!(keys,EXPECTED_KEYS.iter().map(|key|(*key).to_owned()).collect(),"operative source equation mismatch");
    assert!(failures.is_empty(),"{} whole-source failures; {faces_passed}/234 faces passed:\n{}",failures.len(),failures.join("\n"));assert_eq!(faces_passed,234);
}
