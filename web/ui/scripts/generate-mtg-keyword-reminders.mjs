import fs from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import { MTG_KEYWORD_RULES } from '../src/lib/mtg-keyword-rules.generated.js';

export const normalize = value => String(value || '').replace(/[‘’]/g, "'").replace(/[‐‑‒–—―]/g, '-').replace(/\s+/g, ' ').trim().toLowerCase();
const escape = value => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

// Only associate a reminder with a keyword that begins its own line. Never
// infer an explanation from keyword mentions inside another ability/reminder.
export function collectKeywordReminders(cards) {
  const aliases = new Set(MTG_KEYWORD_RULES.flatMap(rule => [rule.title, ...rule.aliases]).map(normalize));
  const candidates = new Map();
  for (const card of cards) {
    if (card.lang && card.lang !== 'en') continue;
    if (card.acorn || card.border_color === 'silver' || card.set_type === 'funny') continue;
    const keywords = (card.keywords || []).map(normalize).filter(keyword => aliases.has(keyword)).sort((a, b) => b.length - a.length);
    for (const face of card.card_faces || [card]) {
      for (const line of (face.oracle_text || '').split('\n')) {
        const match = line.match(/^([^()]+)\(([^()]+)\)\s*$/);
        if (!match) continue;
        const ability = match[1].trim();
        const keyword = keywords.find(word => new RegExp(`^${escape(word)}(?=$|[^\\p{L}\\p{N}_])`, 'iu').test(ability));
        if (!keyword) continue;
        const parameter = ability.slice(keyword.length).trim().replace(/\.$/, '').trim();
        // A full sentence or list preceding parentheses is not a standalone
        // keyword declaration. Leave ambiguous associations to the CR fallback.
        if (/[.!?]/.test(parameter) || /, (?:and )?(?:flying|haste|trample|vigilance|reach|lifelink|menace)\b/i.test(parameter)) continue;
        if (parameter && !keyword.endsWith(' with') && !/^(?:[\dX{—−-]|[“"]|pay\b|discard\b|sacrifice\b|with\b|from\b|for\b|a\b|an\b|to\b)/i.test(parameter)) continue;
        const reminder = match[2].trim();
        const example = Boolean(parameter) || reminder.includes(face.name || card.name) || ['assist', 'compleated', 'station', 'read ahead', 'sunburst', 'haunt', 'indestructible'].includes(keyword);
        const entry = { text: reminder, ...(example ? { example: ability } : {}), card: face.name || card.name };
        const key = JSON.stringify([entry.text, entry.example]);
        if (!candidates.has(keyword)) candidates.set(keyword, new Map());
        const variants = candidates.get(keyword);
        const previous = variants.get(key);
        variants.set(key, { entry: previous && previous.entry.card.localeCompare(entry.card) < 0 ? previous.entry : entry, count: (previous?.count || 0) + 1 });
      }
    }
  }
  return Object.fromEntries([...candidates].sort(([a], [b]) => a.localeCompare(b)).map(([keyword, variants]) => {
    const best = [...variants.values()].sort((a, b) => Number(Boolean(a.entry.example)) - Number(Boolean(b.entry.example)) || b.count - a.count || a.entry.text.length - b.entry.text.length || a.entry.card.localeCompare(b.entry.card))[0];
    return [keyword, best.entry];
  }));
}

async function main() {
  const input = process.argv[2] || new URL('../../../cards.json', import.meta.url);
  const reminders = collectKeywordReminders(JSON.parse(await fs.readFile(input, 'utf8')));
  const output = new URL('../src/lib/mtg-keyword-reminders.generated.js', import.meta.url);
  await fs.writeFile(output, '// Generated by scripts/generate-mtg-keyword-reminders.mjs from cards.json.\nexport const MTG_KEYWORD_REMINDERS = Object.freeze(' + JSON.stringify(reminders, null, 2) + ');\n');
  // The UI resolves duplicate aliases to the first rule in the catalog.
  const coveredRules = new Set(Object.keys(reminders).map(keyword =>
    MTG_KEYWORD_RULES.find(rule => [rule.title, ...rule.aliases].some(alias => normalize(alias) === keyword))?.id
  ));
  console.log(`${Object.keys(reminders).length} keyword names; ${coveredRules.size}/${MTG_KEYWORD_RULES.length} CR entries covered.`);
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) await main();
