import { execFileSync } from 'node:child_process';
import { cp, mkdir, readFile, readdir, writeFile, rm } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../../', import.meta.url));
const source = new URL('../../../vendor/mana/', import.meta.url);
const output = new URL('../public/mana/', import.meta.url);
// Checkout the recorded commit, never the moving upstream branch.
execFileSync('git', ['submodule', 'update', '--init', '--recursive', '--', 'vendor/mana'], { cwd: root, stdio: 'inherit' });
const files = (await readdir(new URL('svg/', source))).filter(name => name.endsWith('.svg'));
if (!files.includes('w.svg')) throw new Error('Mana submodule SVGs are missing');
await rm(output, { recursive: true, force: true });
await mkdir(output, { recursive: true });
await cp(new URL('svg/', source), new URL('svg/', output), { recursive: true });
await cp(new URL('README.md', source), new URL('NOTICE.md', output));
const colors = { W: '#f8f6d8', U: '#c1d7e9', B: '#bab1ab', R: '#e49977', G: '#a3c095', C: '#cac5c0', '2': '#cac5c0' };
const glyphs = {};
for (const file of files) {
  const svg = await readFile(new URL(`svg/${file}`, source), 'utf8');
  const viewBox = svg.match(/viewBox="([^"]+)"/)[1];
  glyphs[file.slice(0, -4)] = { viewBox, body: svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>[\s\S]*$/, '').replace(/<title>[\s\S]*?<\/title>/g, '').replaceAll('#444', '#0d0f0f') };
}
const glyph = (name, x = 15, y = 15, size = 70) => `<svg x="${x}" y="${y}" width="${size}" height="${size}" viewBox="${glyphs[name].viewBox}">${glyphs[name].body}</svg>`;
const save = async (code, body) => writeFile(new URL(`symbols/${code.replaceAll('/', '-')}.svg`, output), `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100">${body}</svg>`);
await mkdir(new URL('symbols/', output));
const codes = {};
for (const name of [...Object.keys(colors), ...Array.from({length: 21}, (_, i) => String(i)), '100', '1000000', 'X', 'Y', 'Z', 'S', 'T', 'Q', 'E', 'P', 'CHAOS', 'INFINITY', 'TK', 'A']) {
  const asset = ({ T: 'tap', Q: 'untap', TK: 'ticket', A: 'acorn', INFINITY: 'infinity' })[name] || name.toLowerCase();
  await save(name, `<circle cx="50" cy="50" r="50" fill="${colors[name] || '#cac5c0'}"/>${glyph(asset)}`);
  codes[name] = name.replaceAll('/', '-');
}
for (const left of ['W', 'U', 'B', 'R', 'G', 'C', '2']) {
  for (const right of ['W', 'U', 'B', 'R', 'G']) {
    if (left === right) continue;
    const background = `<circle cx="50" cy="50" r="50" fill="${colors[left]}"/><path d="M85.355 14.645A50 50 0 0 1 14.645 85.355Z" fill="${colors[right]}"/>`;
    for (const phyrexian of [false, true]) {
      if (phyrexian && ['2', 'C'].includes(left)) continue;
      const code = `${left}/${right}${phyrexian ? '/P' : ''}`;
      await save(code, background + (phyrexian ? glyph('p') : glyph(left.toLowerCase(), 9, 9, 43) + glyph(right.toLowerCase(), 48, 48, 43)));
      codes[code] = code.replaceAll('/', '-');
    }
  }
  if (left !== '2') {
    const code = `${left}/P`;
    await save(code, `<circle cx="50" cy="50" r="50" fill="${colors[left]}"/>${glyph('p')}`);
    codes[code] = code.replaceAll('/', '-');
  }
}
await writeFile(new URL('../src/lib/mana-assets.generated.js', import.meta.url), `// Generated by scripts/sync-mana-assets.mjs.\nexport const manaAssets = ${JSON.stringify(codes, null, 2)};\nexport const manaGlyphs = ${JSON.stringify(files.map(file => file.slice(0, -4)))};\n`);
console.log(`Prepared ${files.length} Mana SVGs and ${Object.keys(codes).length} cost symbols.`);
