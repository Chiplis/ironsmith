// Precomputes the random-table classification of every compiled card, so the
// startup board is sampled locally instead of reading hundreds of card assets
// just to learn their types. Classification reuses the app's own classifyCard,
// so the pool accepts exactly the cards the per-asset walk would have.
//
// Output lives beside cards/, not inside it: every *.json in cards/ is a route
// the registry generator owns (and deletes when it is not a live route).
import { readFile, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { classifyCard } from "../src/lib/random-game.js";
import { RANDOM_CARD_POOL_FORMAT } from "../src/lib/random-card-pool.js";

const uiRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const cardsDir = path.join(uiRoot, "public", "cards");
const indexPath = path.join(cardsDir, "index.json");
const checksumPath = path.join(cardsDir, ".ironsmith_frontend_cards_checksum");
const outputPath = path.join(uiRoot, "public", "random-card-pool.json");
const READ_CONCURRENCY = 64;

async function readJson(file) {
  try {
    return JSON.parse(await readFile(file, "utf8"));
  } catch (error) {
    if (error.code === "ENOENT") return null;
    throw error;
  }
}

async function cardsFingerprint() {
  const manifest = await readJson(checksumPath);
  const indexStat = await stat(indexPath);
  // The checksum is only moved into place after artifacts are baked; the index
  // size and mtime also catch a card directory regenerated by other means.
  return `${manifest?.checksum || "unversioned"}:${indexStat.size}:${Math.trunc(indexStat.mtimeMs)}`;
}

async function main() {
  const index = await readJson(indexPath);
  if (!Array.isArray(index?.cards)) {
    console.log("No public/cards/index.json; skipping the random card pool. The app falls back to reading card assets.");
    return;
  }
  const fingerprint = await cardsFingerprint();
  const existing = await readJson(outputPath);
  if (existing?.format === RANDOM_CARD_POOL_FORMAT && existing?.cardsFingerprint === fingerprint
    && !process.argv.includes("--force")) {
    console.log(`Random card pool is current (${existing.cards.length} cards)`);
    return;
  }

  const startedAt = Date.now();
  const routes = [...new Set(index.cards.map((card) => String(card?.route || "").trim()).filter(Boolean))];
  const classified = new Array(routes.length);
  let cursor = 0;
  await Promise.all(Array.from({ length: READ_CONCURRENCY }, async () => {
    while (cursor < routes.length) {
      const slot = cursor++;
      const asset = await readJson(path.join(cardsDir, `${routes[slot]}.json`));
      classified[slot] = asset ? classifyCard(asset) : null;
    }
  }));

  const dictionaries = { types: [], supertypes: [], colors: [] };
  const code = (dictionary, value) => {
    let at = dictionaries[dictionary].indexOf(value);
    if (at < 0) at = dictionaries[dictionary].push(value) - 1;
    return at;
  };
  const seen = new Set();
  const cards = [];
  for (const card of classified) {
    // Alias routes share one payload; the pool lists each card once.
    if (!card || seen.has(card.name)) continue;
    seen.add(card.name);
    cards.push([
      card.name,
      card.types.map((type) => code("types", type)),
      card.supertypes.map((type) => code("supertypes", type)),
      card.colors.map((color) => code("colors", color)),
      card.manaValue,
      card.singleFaced ? 1 : 0,
      card.score,
    ]);
  }
  cards.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
  await writeFile(outputPath, JSON.stringify({
    format: RANDOM_CARD_POOL_FORMAT,
    cardsFingerprint: fingerprint,
    ...dictionaries,
    cards,
  }));
  console.log(`Random card pool: ${cards.length} of ${routes.length} routes classified in ${Date.now() - startedAt}ms`);
}

await main();
