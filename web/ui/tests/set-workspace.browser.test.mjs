import test from 'node:test';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { createServer } from 'vite';
import { mkdir } from 'node:fs/promises';

test('set cards and mechanics can be revised and persisted independently of the personal library', { timeout: 90000 }, async () => {
  const server = await createServer({ server: { host: '127.0.0.1', port: 0, hmr: false }, logLevel: 'error' });
  await server.listen();
  const browser = await chromium.launch();
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.route('https://**', route => route.abort());
    await page.route('**/custommagic/pool.json', route => route.fulfill({ json: { cards: [] } }));
    await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/tests/build-workspace.html`);
    const button = name => page.getByRole('button', { name, exact: true });
    await button('Build').click();
    await page.getByRole('tab', { name: 'Sets', exact: true }).click();
    await page.getByLabel('Custom set name', { exact: true }).fill('Embers of the Wild');
    await page.getByRole('button', { name: /Set mechanics/ }).click();
    await page.getByLabel('Keyword', { exact: true }).fill('Kindle');
    await page.getByLabel('Reminder text', { exact: true }).fill('Draw a card.');
    await button('Save mechanic').click();
    await button('kindle').waitFor();
    await page.getByRole('button', { name: /Set cards/ }).click();
    await button('Create card in set').click();
    await page.getByLabel('Card name', { exact: true }).fill('Emberwake Insight');
    await button('Creature').click();
    await button('Sorcery').click();
    await page.getByRole('textbox', { name: 'Rules text', exact: true }).fill('Kindle');
    await button('Save to set').click();
    await page.getByText('Saved Emberwake Insight to Embers of the Wild.', { exact: true }).waitFor();
    await mkdir('test-results/set-workspace', { recursive: true });
    await page.waitForFunction(() => document.querySelector('[data-card-glint-live]')?.dataset.cardGlintLive === 'static');
    await page.screenshot({ path: 'test-results/set-workspace/card-editor.png' });
    await page.getByLabel('Card name', { exact: true }).fill('Unsaved set draft');
    await button('Edit set mechanic kindle').click();
    await page.getByRole('heading', { name: 'Edit set mechanic', exact: true }).waitFor();
    assert.equal(await page.getByLabel('Keyword', { exact: true }).inputValue(), 'kindle');
    assert.equal(await page.getByRole('tab', { name: 'Sets', exact: true }).getAttribute('aria-selected'), 'true');
    assert.equal(await page.getByRole('tab', { name: 'Mechanics', exact: true }).getAttribute('aria-selected'), 'false');
    await button('Back to card').click();
    assert.equal(await page.getByLabel('Card name', { exact: true }).inputValue(), 'Unsaved set draft');
    await page.getByRole('tab', { name: 'Mechanics', exact: true }).click();
    await button('Back to card').waitFor();
    assert.equal(await page.getByRole('button', { name: /Set mechanics/ }).getAttribute('aria-pressed'), 'true');
    await button('Back to card').click();
    assert.equal(await page.getByLabel('Card name', { exact: true }).inputValue(), 'Unsaved set draft');
    await button('Back to set').click();
    await button('Edit Emberwake Insight').click();
    await page.getByLabel('Card name', { exact: true }).fill('Rekindled Insight');
    await button('Save to set').click();
    await page.getByText('Saved Rekindled Insight to Embers of the Wild.', { exact: true }).waitFor();
    await button('Back to set').click();
    assert.equal(await button('Edit Emberwake Insight').count(), 0);
    await page.getByRole('button', { name: /Set mechanics/ }).click();
    await button('kindle').click();
    await page.getByLabel('Reminder text', { exact: true }).fill('Draw two cards.');
    await button('Update mechanic').click();
    await page.getByRole('heading', { name: 'New custom mechanic', exact: true }).waitFor();
    await button('Save set').click();
    await page.getByRole('status').filter({ hasText: 'Set saved.' }).waitFor();
    await button('kindle').click();
    await page.getByText('Reminder text compiles.', { exact: true }).waitFor();
    await page.screenshot({ path: 'test-results/set-workspace/mechanics.png' });
    const library = await page.evaluate(async () => {
      const { loadCommunityLibrary } = await import('/src/lib/community-library.js');
      const { listSavedCustomCards, listCustomMechanics } = await import('/src/lib/custom-card-library.js');
      return { community: await loadCommunityLibrary(), cards: await listSavedCustomCards(), mechanics: await listCustomMechanics() };
    });
    assert.equal(library.community.sets[0].cards.length, 1);
    assert.equal(library.community.sets[0].cards[0].draft.customMechanics[0].reminder, 'Draw two cards.');
    assert.deepEqual(library.cards, []);
    assert.deepEqual(library.mechanics, []);
    await page.reload({ waitUntil: 'domcontentloaded' });
    await button('Build').click();
    await page.getByRole('tab', { name: 'Sets', exact: true }).click();
    await page.getByLabel('Saved sets', { exact: true }).selectOption('0');
    await button('Edit Rekindled Insight').waitFor();
    await page.screenshot({ path: 'test-results/set-workspace/overview.png' });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: 'test-results/set-workspace/mobile.png' });
    assert.deepEqual(errors, []);
  } finally { await browser.close(); await server.close(); }
});
