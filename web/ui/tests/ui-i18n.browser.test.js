import test from 'node:test';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { createServer } from 'vite';
test('dialogs, phase guidance and keyword help switch languages without losing input', async () => {
  const vite = await createServer({server:{host:'127.0.0.1',port:0},logLevel:'silent'});
  await vite.listen();
  const browser = await chromium.launch();
  try {
    const page = await browser.newPage({viewport:{width:1200,height:1000}});
    const errors=[]; page.on('pageerror',error=>errors.push(error.message));
    await page.goto(`http://127.0.0.1:${vite.httpServer.address().port}/tests/ui-i18n.html`);
    await page.getByRole('button',{name:'Random fixture'}).waitFor();
    await page.evaluate(()=>window.__setTestLocale('es'));
    await page.getByText('Mantenimiento',{exact:true}).waitFor();
    await page.getByRole('button',{name:'Explicar la fase actual'}).click();
    const tooltip=page.locator('[data-ui-layer="tooltip"][data-state="open"]');
    await tooltip.waitFor();
    assert.match(await tooltip.innerText(), /Puedes activar una habilidad/);
    assert.doesNotMatch(await tooltip.innerText(), /You can|Upkeep triggers|Draw/);
    await page.keyboard.press('Escape');
    await page.locator('[data-keyword-probe] .mtg-keyword-helper').click();
    await tooltip.waitFor();
    assert.match(await tooltip.innerText(), /Vuela/iu);
    assert.doesNotMatch(await tooltip.innerText(), /A keyword ability/);
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('[data-localized-keyword-probe] .mtg-keyword-helper').count(),1);
    await page.locator('[data-mana-probe] [aria-label]').click();
    await tooltip.waitFor();
    assert.match(await tooltip.innerText(), /maná blanco o maná azul/iu);
    assert.doesNotMatch(await tooltip.innerText(), /White|Blue|This hybrid/);
    await page.keyboard.press('Escape');
    await page.getByRole('button',{name:'Random fixture'}).click();
    await page.getByRole('heading',{name:'Partida aleatoria',exact:true}).waitFor();
    assert.equal(await page.getByText('Criatura',{exact:true}).count(),1);
    assert.equal(await page.getByText('Blanco',{exact:true}).count(),1);
    const seed=page.getByPlaceholder('aleatoria',{exact:true});
    await seed.fill('Main');
    await page.evaluate(()=>window.__setTestLocale('en'));
    await page.getByRole('heading',{name:'Random Game',exact:true}).waitFor();
    assert.equal(await page.getByPlaceholder('random',{exact:true}).inputValue(),'Main');
    await page.keyboard.press('Escape');
    await page.getByRole('button',{name:'Add fixture'}).click();
    await page.evaluate(()=>window.__setTestLocale('es'));
    await page.getByRole('heading',{name:'Añadir carta',exact:true}).waitFor();
    assert.equal(await page.getByRole('option',{name:'Main',exact:true}).count(),1);
    assert.deepEqual(errors,[]);
  } finally {await browser.close(); await vite.close();}
});
