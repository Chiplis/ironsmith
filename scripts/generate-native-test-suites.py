#!/usr/bin/env python3
"""Group integration tests into stable suites without moving their source files.

Run after adding/removing a test file; --check verifies generated files without
writing them. The suite coverage test also catches files missing from a suite.
"""

import argparse
import hashlib
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
PACKAGES = {"ironsmith-compiler-runtime": 24, "ironsmith-tools": 16}
BEGIN = "# BEGIN GENERATED NATIVE TEST SUITES"
END = "# END GENERATED NATIVE TEST SUITES"


def outputs(root=ROOT):
    result = {}
    for package, count in PACKAGES.items():
        directory = root / "crates" / package
        tests = directory / "tests"
        sources = sorted(tests.glob("*.rs")) + sorted(tests.glob("*/main.rs"))
        suites = [[] for _ in range(count)]
        names = set()
        for source in sources:
            name = source.parent.name if source.name == "main.rs" else source.stem
            if not re.fullmatch(r"[a-zA-Z_][a-zA-Z_0-9]*", name) or name in names:
                raise ValueError(f"invalid or duplicate test module name: {source}")
            names.add(name)
            # Unlike Python's hash(), this assignment is stable across processes.
            bucket = int.from_bytes(hashlib.sha256(name.encode()).digest()[:8], "big") % count
            suites[bucket].append((name, source.relative_to(tests).as_posix()))

        manifest = directory / "Cargo.toml"
        original = manifest.read_text()
        if "autotests = false" not in original:
            original = original.replace("[package]\n", "[package]\nautotests = false\n", 1)
        declarations = [BEGIN, "# Regenerate with python3 scripts/generate-native-test-suites.py."]
        for index, entries in enumerate(suites):
            name = f"suite_{index:02}"
            source = ["// Generated by scripts/generate-native-test-suites.py; do not edit."]
            if index == 0:
                source += [
                    '#[path = "../../../../scripts/native-test-suite-coverage.rs"]',
                    "mod suite_coverage;",
                    "",
                ]
            for module, path in sorted(entries):
                source += [f'#[path = "../{path}"]', f"mod r#{module};", ""]
            result[tests / "suites" / f"{name}.rs"] = "\n".join(source)
            declarations += ["", "[[test]]", f'name = "{name}"', f'path = "tests/suites/{name}.rs"']
        declarations += [END]
        block = "\n".join(declarations)
        if BEGIN in original:
            original = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, original, flags=re.S)
        else:
            original = original.rstrip() + "\n\n" + block + "\n"
        result[manifest] = original
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, content in outputs().items():
        if path.exists() and path.read_text() == content:
            continue
        stale.append(path.relative_to(ROOT))
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if args.check and stale:
        print("Test suites are stale; run python3 scripts/generate-native-test-suites.py", file=sys.stderr)
        for path in stale:
            print(f"  {path}", file=sys.stderr)
        return 1
    print(f"Native test suites: {sum(PACKAGES.values())} executables; {len(stale)} files "
          + ("need updating" if args.check else "updated"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
